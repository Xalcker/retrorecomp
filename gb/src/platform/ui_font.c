#undef _

#define NUM_GLYPHS (int)(sizeof glyphs / sizeof glyphs[0])

/* Bits listos para dibujar: una máscara de 5 bits por fila */
static unsigned char bits[NUM_GLYPHS][UI_GLYPH_H];
static int ready;

static void prepare(void)
{
    for (int g = 0; g < NUM_GLYPHS; g++)
        for (int r = 0; r < UI_GLYPH_H; r++) {
            unsigned char m = 0;
            for (int c = 0; c < UI_GLYPH_W; c++)
                if (glyphs[g].rows[r][c] == '#') m |= (unsigned char)(1 << c);
            bits[g][r] = m;
        }
    ready = 1;
}

/* Decodifica un carácter UTF-8 y avanza el puntero */
static unsigned next_codepoint(const char **s)
{
    const unsigned char *p = (const unsigned char *)*s;
    unsigned c = *p++;
    if (c >= 0xF0 && p[0] && p[1] && p[2]) {
        c = (c & 0x07) << 18 | (p[0] & 0x3Fu) << 12 | (p[1] & 0x3Fu) << 6 | (p[2] & 0x3Fu);
        p += 3;
    } else if (c >= 0xE0 && p[0] && p[1]) {
        c = (c & 0x0F) << 12 | (p[0] & 0x3Fu) << 6 | (p[1] & 0x3Fu);
        p += 2;
    } else if (c >= 0xC0 && p[0]) {
        c = (c & 0x1F) << 6 | (p[0] & 0x3Fu);
        p += 1;
    }
    *s = (const char *)p;
    return c;
}

/* Las mayúsculas acentuadas se dibujan sin acento */
static unsigned fold(unsigned c)
{
    switch (c) {
    case 0xC1: return 'A';
    case 0xC9: return 'E';
    case 0xCD: return 'I';
    case 0xD3: return 'O';
    case 0xDA: return 'U';
    case 0xD1: return 'N';
    default: return c;
    }
}

static int find(unsigned c)
{
    c = fold(c);
    for (int g = 0; g < NUM_GLYPHS; g++)
        if (glyphs[g].codepoint == c) return g;
    return -1;
}

int ui_text_width(const char *s, int scale)
{
    int n = 0;
    while (*s) {
        next_codepoint(&s);
        n++;
    }
    return n * UI_ADVANCE * scale;
}

void ui_draw_text(SDL_Renderer *ren, int x, int y, int scale, const char *s, SDL_Color color)
{
    if (!ready) prepare();
    SDL_SetRenderDrawColor(ren, color.r, color.g, color.b, color.a);

    SDL_Rect rects[UI_GLYPH_W * UI_GLYPH_H];
    while (*s) {
        unsigned c = next_codepoint(&s);
        int g = find(c);
        if (g < 0) g = find('?');
        int n = 0;
        for (int r = 0; r < UI_GLYPH_H; r++)
            for (int col = 0; col < UI_GLYPH_W; col++)
                if (bits[g][r] & (1 << col))
                    rects[n++] = (SDL_Rect){ x + col * scale, y + r * scale, scale, scale };
        if (n) SDL_RenderFillRects(ren, rects, n);
        x += UI_ADVANCE * scale;
    }
}
